def _num(raw: Any, what: str) -> float:
    try:
        v = float(raw)
    except (TypeError, ValueError):
        raise CampEventError(f"{what} must be a number")
    if not math.isfinite(v):
        raise CampEventError(f"{what} must be a finite number")
    return v


def _point(raw: Any, what: str, default_facing: float = DEFAULT_FACING) -> dict:
    if not isinstance(raw, dict):
        raise CampEventError(f"{what} must be an object with x, y and facing")
    return {"x": _num(raw.get("x"), f"{what}.x"), "y": _num(raw.get("y"), f"{what}.y"),
            "facing": _num(raw.get("facing", default_facing), f"{what}.facing") % 360}


def parse_camp_event(raw: Any, plan_id: str) -> Optional[dict]:
    """Normalise the plan's `camp_event` block (None when absent or disabled)."""
    if raw in (None, False, {}) or (isinstance(raw, dict) and raw.get("enabled") is False):
        return None
    if not isinstance(raw, dict):
        raise CampEventError("camp_event must be an object")
    script = str(raw.get("script") or default_script(plan_id)).strip().lower()
    if not SCRIPT_RE.match(script):
        raise CampEventError(f"camp_event.script {script!r}: use 1-16 chars of a-z, 0-9, _")
    try:
        raw_weight = raw.get("weight", 1)
        weight = 1 if raw_weight in (None, "") else int(raw_weight)
    except (TypeError, ValueError):
        raise CampEventError("camp_event.weight must be a whole number")
    if not 1 <= weight <= MAX_WEIGHT:
        raise CampEventError(f"camp_event.weight must be 1-{MAX_WEIGHT} (event slots used)")
    origin = _point(raw["origin"], "camp_event.origin") if raw.get("origin") not in (None, {}) else None
    spots_in = raw.get("spots") or []
    if not isinstance(spots_in, list):
        raise CampEventError("camp_event.spots must be a list")
    if len(spots_in) > MAX_SPOTS:
        raise CampEventError(f"camp_event.spots: at most {MAX_SPOTS} spots")
    spots = [_point(s, f"camp_event.spots[{i}]") for i, s in enumerate(spots_in)]
    group = raw.get("replaces_group")
    if group in (None, "", 0):
        group = None
    else:
        try:
            group = int(group)
        except (TypeError, ValueError):
            raise CampEventError("camp_event.replaces_group must be 1-9")
        if not 1 <= group <= 9:
            raise CampEventError("camp_event.replaces_group must be 1-9")
    radius = _num(raw.get("replace_radius", 0) or 0, "camp_event.replace_radius")
    if not 0 <= radius <= 300:
        raise CampEventError("camp_event.replace_radius must be 0-300 m (0 = the whole group)")
    return {"script": script, "gate": gate_script_name(script), "weight": weight, "origin": origin, "spots": spots,
            "include_origin": bool(raw.get("include_origin", False)), "replaces_group": group,
            "replace_radius": radius}


