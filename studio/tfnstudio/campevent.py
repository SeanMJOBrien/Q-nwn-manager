MAX_SPOTS = 24
MAX_WEIGHT = 4
MAX_EVENT_SLOTS = 9                    # area_init counts at most event1..event9
DEFAULT_EVENT_CHANCE = 50              # area_refresh.nss: event_chance <= 0 means 50
EVENT_PREFIX = "eve_"
GATE_PREFIX = "spw_"
MARKER_BLUEPRINT = "nw_waypoint001"    # stock waypoint blueprint, created as the tagged "camp is standing" marker
EVENT_WP_RESREF = "_wp_event"
SPOT_TAG_PREFIX = "camp_spot"          # hand-placed waypoints with this tag prefix can be imported as spots
DEFAULT_FACING = 90.0                  # template and spot arrows point north unless told otherwise
SPOT_SPACING_WARN = 2.0                # spots closer than this (metres) are probably duplicates
SCRIPT_RE = re.compile(r"^[a-z0-9_]{1,16}$")
TAG_RE = re.compile(r"^[A-Za-z0-9_ ,.'()+-]{0,32}$")
_HEADER_RE = re.compile(r"^// tfn-studio camp (event|gate): plan ([a-z0-9_]+)", re.M)
_CHAIN_RE = re.compile(r"^// tfn-studio chains: (\S+)[ \t]*$", re.M)


class CampEventError(ProjectError):
    """Unusable `camp_event` settings (the camps module re-raises these as PlanError)."""


