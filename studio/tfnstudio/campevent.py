# spot suggestions
# ---------------------------------------------------------------------------------------------------------------------

SUGGEST_DIRECTIONS = tuple(range(0, 360, 45))
NOMINAL_FOOTPRINT = ((0.0, 0.0), (2.0, 0.0), (-2.0, 0.0), (0.0, 2.0), (0.0, -2.0))   # when the plan has no objects yet


def suggest_spots(grid: Any, are_w: float, are_h: float, objs: list[dict], origin: dict, existing: list[tuple[float, float]],
                  count: int, seed: str, taken: Optional[list[tuple[float, float]]] = None) -> list[dict]:
    """Up to `count` well-spread spots where the camp really fits, each turned (in 45 degree steps) towards the area centre.

    A spot is only suggested when the camp's own objects, moved and turned there, all stand on walkable ground (creatures also
    need free ground around them) and keep clear of the area's existing objects: the same checks staging makes per spot.
    `grid` is a walkmesh WalkGrid (1 m cells, 1 = walkable).  Deterministic for a given seed; spots stay clear of `taken` ones.
    """
    taken = taken or []
    rng = random.Random(seed)
    width, height, rows = grid.width, grid.height, grid.rows
    if objs:
        rel = [(o["x"] - origin["x"], o["y"] - origin["y"], o["kind"] == "creature") for o in objs]
    else:
        rel = [(dx, dy, False) for dx, dy in NOMINAL_FOOTPRINT]
    radius = max(math.hypot(dx, dy) for dx, dy, _c in rel)

    def walkable(x: float, y: float) -> bool:
        if not (0.5 <= x <= width - 0.5 and 0.5 <= y <= height - 0.5):       # staging keeps 0.5 m from the area's edge
            return False
        return rows[int(y)][int(x)] == 1

    buckets: dict[tuple[int, int], list[tuple[float, float]]] = {}
    for ex, ey in existing:
        buckets.setdefault((int(ex // 4), int(ey // 4)), []).append((ex, ey))

    def crowded(x: float, y: float, clear: float) -> bool:
        reach = int(clear // 4) + 1
        bx, by = int(x // 4), int(y // 4)
        for i in range(bx - reach, bx + reach + 1):
            for j in range(by - reach, by + reach + 1):
                for ex, ey in buckets.get((i, j), ()):
                    if math.hypot(ex - x, ey - y) < clear:
                        return True
        return False

    stride = width + 1
    sat = [0] * (stride * (height + 1))              # summed-area table of walkable cells: a cheap first filter
    for y in range(height):
        row = rows[y]
        for x in range(width):
            v = 1 if row[x] == 1 else 0
            sat[(y + 1) * stride + x + 1] = v + sat[y * stride + x + 1] + sat[(y + 1) * stride + x] - sat[y * stride + x]
    r = int(math.ceil(radius)) + 1
    side = 2 * r + 1
    step = max(1, int(math.sqrt(width * height / 25600.0) + 0.5))        # big areas: look at every 2nd/3rd metre
    turns = [(f, math.cos(math.radians(f - origin["facing"])), math.sin(math.radians(f - origin["facing"])))
             for f in SUGGEST_DIRECTIONS]
    pool: list[tuple[float, float, int]] = []
    for yi in range(1, height - 1, step):
        for xi in range(1, width - 1, step):
            if rows[yi][xi] != 1:
                continue
            x0, y0, x1, y1 = max(0, xi - r), max(0, yi - r), min(width, xi + r + 1), min(height, yi + r + 1)
            if (sat[y1 * stride + x1] - sat[y0 * stride + x1] - sat[y1 * stride + x0] + sat[y0 * stride + x0]) < 0.3 * side * side:
                continue
            px, py = xi + 0.5, yi + 0.5
            if crowded(px, py, 2.5):
                continue
            to_centre = math.degrees(math.atan2(are_h / 2 - py, are_w / 2 - px)) % 360
            best: Optional[int] = None
            best_gap = 361.0
            for facing, c, sn in turns:
                ok = True
                for dx, dy, creature in rel:
                    x, y = px + dx * c - dy * sn, py + dx * sn + dy * c
                    if not walkable(x, y) or crowded(x, y, 1.5):
                        ok = False
                        break
                    if creature and not (walkable(x + 1, y) and walkable(x - 1, y) and walkable(x, y + 1) and walkable(x, y - 1)):
                        ok = False
                        break
                if ok:
                    gap = abs((facing - to_centre + 180) % 360 - 180)
                    if gap < best_gap:
                        best, best_gap = facing, gap
            if best is not None:
                pool.append((px, py, best))
    min_sep = max(2.0 * radius + 2.0, 10.0)
    pool = [c for c in pool if all(math.hypot(c[0] - tx, c[1] - ty) >= min_sep for tx, ty in taken)]
    if not pool or count < 1:
        return []
    chosen = [pool[rng.randrange(len(pool))]]
    while len(chosen) < count:
        far: Optional[tuple[float, float, int]] = None
        far_d = -1.0
        for c in pool:
            d = min(math.hypot(c[0] - sx, c[1] - sy) for sx, sy, _f in chosen)
            if d > far_d:
                far, far_d = c, d
        if far is None or far_d < min_sep:
            break
        chosen.append(far)
    return [{"x": round(px, 2), "y": round(py, 2), "facing": float(f)} for px, py, f in chosen]
