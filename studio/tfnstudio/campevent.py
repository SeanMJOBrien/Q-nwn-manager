def _short(core: str, limit: int) -> str:
    """`core` cut to `limit` characters; a hash suffix keeps different long names apart."""
    if len(core) <= limit:
        return core
    digest = hashlib.sha1(core.encode("utf-8")).hexdigest()
    return core[: limit - 5].rstrip("_") + "_" + digest[:4]


def default_script(plan_id: str) -> str:
    """eve_<id>, at most 16 characters (the resref limit for scripts)."""
    core = re.sub(r"[^a-z0-9_]", "_", plan_id.lower())
    if core.startswith(EVENT_PREFIX):
        core = core[len(EVENT_PREFIX):]
    return EVENT_PREFIX + _short(core, 16 - len(EVENT_PREFIX))


def gate_script_name(event_script: str) -> str:
    core = event_script[len(EVENT_PREFIX):] if event_script.startswith(EVENT_PREFIX) else event_script
    return GATE_PREFIX + _short(core, 16 - len(GATE_PREFIX))


def camp_tag(plan_id: str) -> str:
    """Tag of the marker waypoint that exists while the camp stands (object tags are limited to 32 characters)."""
    return "ce_" + _short(plan_id, 32 - 3)


def generated_by(text: Optional[str]) -> Optional[tuple[str, str]]:
    """(kind, plan id) when `text` is a script generated by this module, else None."""
    if not text:
        return None
    m = _HEADER_RE.search(text[:800])
    return (m.group(1), m.group(2)) if m else None


def chain_of(text: Optional[str]) -> str:
    """The spawn script a generated gate chains to ("" when it has none)."""
    if not text:
        return ""
    m = _CHAIN_RE.search(text[:1000])
    return "" if not m or m.group(1) == "-" else m.group(1)


def check_script_free(existing: Optional[str], kind: str, plan_id: str, name: str, *, elsewhere: bool = False) -> None:
    """Refuse to overwrite a script this plan did not generate (TFN's own `eve_bears`, another plan's camp, a base-game script)."""
    if elsewhere:
        raise CampEventError(f"{name!r} is a base-game script name: choose another script name")
    if existing is None:
        return
    owner = generated_by(existing)
    if owner != (kind, plan_id):
        who = "another tool or plan" if owner is None else f"the {owner[0]} script of plan {owner[1]!r}"
        raise CampEventError(f"src/nss/{name}.nss already exists and belongs to {who}, not to this plan: choose another script name")


def comment_text(text: str, limit: int = 80) -> str:
    """Plain ASCII on one line, safe inside a `//` comment."""
    return re.sub(r"\s+", " ", text.encode("ascii", "replace").decode("ascii")).strip()[:limit]


