@dataclass
class Wiring:
    script: str
    slots: list[int] = field(default_factory=list)          # eventN slots now holding our script
    event_chance: int = DEFAULT_EVENT_CHANCE
    chance_is_default: bool = True
    slots_total: int = 0                                      # contiguous event slots, as area_init counts them
    effective: float = 0.0                                    # chance per refresh that our camp appears
    event_waypoints: int = 0
    other_events: list[str] = field(default_factory=list)
    gate: Optional[dict] = None
    notes: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"script": self.script, "slots": self.slots, "event_chance": self.event_chance,
                "chance_is_default": self.chance_is_default, "slots_total": self.slots_total,
                "effective": self.effective, "event_waypoints": self.event_waypoints,
                "other_events": self.other_events, "gate": self.gate, "notes": self.notes, "warnings": self.warnings}


@dataclass
class EventPlan:
    """Everything the builder works out for one plan's camp event (the preview API returns the same data without staging)."""
    ce: dict
    origin: dict
    origin_is_default: bool
    footprint: float
    template: list[dict]
    variants: list[Variant]
    wiring: Wiring
    event_source: str
    gate_source: Optional[str]
    added_waypoint: Optional[dict]

    @property
    def errors(self) -> list[str]:
        return [m for v in self.variants for m in v.errors]

    def to_dict(self) -> dict:
        return {"enabled": True, "script": self.ce["script"], "gate": self.ce["gate"] if self.ce["replaces_group"] else None,
                "weight": self.ce["weight"], "origin": self.origin, "origin_is_default": self.origin_is_default,
                "footprint": round(self.footprint, 2), "variants": [v.to_dict() for v in self.variants],
                "wiring": self.wiring.to_dict(), "added_waypoint": self.added_waypoint, "errors": self.errors}


def event_run(git: dict) -> list[str]:
    """The event scripts the game sees: event1.. up to the first empty slot (area_init)."""
    gv = G.vars_of(git)
    out: list[str] = []
    for n in range(1, MAX_EVENT_SLOTS + 1):
        name = gv.get(f"event{n}")
        if not isinstance(name, str) or not name:
            break
        out.append(name)
    return out


def plan_event_run(current: list[str], script: str, weight: int) -> list[str]:
    """The contiguous event list after giving `script` exactly `weight` slots (keeps its place, appends what is missing)."""
    out: list[str] = []
    mine = 0
    for name in current:
        if name == script:
            if mine < weight:
                out.append(name)
                mine += 1
        else:
            out.append(name)
    out.extend([script] * (weight - mine))
    return out


def write_event_run(git: dict, run: list[str]) -> list[str]:
    """Store `run` as event1..eventN, clearing the rest of the old run. Returns warnings about newly reachable orphan slots."""
    gv = G.vars_of(git)
    old_len = len(event_run(git))
    for n, name in enumerate(run, 1):
        if gv.get(f"event{n}") != name:
            G.set_var(git, f"event{n}", name)
    for n in range(len(run) + 1, max(old_len, len(run)) + 1):
        G.del_var(git, f"event{n}")
    warnings = []
    after = len(event_run(git))
    if after > len(run):
        warnings.append(f"event{len(run) + 1}..event{after} were set but unreachable before (they follow an empty slot); "
                        "they are part of the area's events now")
    return warnings


def event_waypoints(git: dict) -> list[dict]:
    """The area's `_wp_event` waypoints as {x, y, z, facing, tag, plan}."""
    out = []
    for inst in I.instances(git, "waypoint"):
        if G.get(inst, "TemplateResRef", "") != EVENT_WP_RESREF:
            continue
        x, y, z = I.position_of("waypoint", inst)
        out.append({"x": x, "y": y, "z": z, "tag": G.get(inst, "Tag", ""), "plan": G.get_var(inst, I.PLAN_VAR, ""),
                    "facing": facing_of(inst)})
    return out


def facing_of(inst: dict) -> float:
    """Facing in degrees (0 = east, 90 = north) of a creature/waypoint instance from its orientation vector."""
    xo, yo = G.get(inst, "XOrientation", 0.0), G.get(inst, "YOrientation", 1.0)
    return round(math.degrees(math.atan2(yo, xo)) % 360, 2)


def waypoint_spots(git: dict, exclude_plan: str = "") -> list[dict]:
    """Hand-placed markers that can be imported as spots: `_wp_event` waypoints and waypoints tagged `camp_spot*`.

    Waypoints generated by the plan `exclude_plan` are left out (they are the plan's own output)."""
    out = []
    for inst in I.instances(git, "waypoint"):
        res, tag = G.get(inst, "TemplateResRef", ""), G.get(inst, "Tag", "")
        if exclude_plan and G.get_var(inst, I.PLAN_VAR, "") == exclude_plan:
            continue
        if res != EVENT_WP_RESREF and not tag.lower().startswith(SPOT_TAG_PREFIX):
            continue
        x, y, z = I.position_of("waypoint", inst)
        out.append({"x": round(x, 2), "y": round(y, 2), "z": round(z, 2), "facing": facing_of(inst), "tag": tag,
                    "resref": res, "source": "event waypoint" if res == EVENT_WP_RESREF else f"tag {tag}"})
    return out


def release_stale(git: dict, read_script: Callable[[str], Optional[str]], plan_id: str, event_script: Optional[str],
                  gate: Optional[tuple[str, int]]) -> list[str]:
    """Undo the wiring of scripts this plan generated earlier but no longer wants (it left event mode, renamed the script,
    now replaces another group, ...).  `gate` is (gate script name, group) when the plan still replaces a group."""
    notes = []
    run = event_run(git)
    keep = [name for name in run if not (name != event_script and generated_by(read_script(name)) == ("event", plan_id))]
    if keep != run:
        gone = sorted({n for n in run if n not in keep})
        notes.extend(write_event_run(git, keep))
        notes.append("removed the event slot(s) of " + ", ".join(repr(n) for n in gone)
                     + ": camp script(s) of this plan that are no longer used")
    for n in range(1, 10):
        var = f"random{n}_spawn_script"
        name = G.get_var(git, var)
        if not isinstance(name, str) or not name:
            continue
        if gate and name == gate[0] and n == gate[1]:
            continue
        text = read_script(name)
        if generated_by(text) == ("gate", plan_id):
            chain = chain_of(text)
            if chain:
                G.set_var(git, var, chain)
            else:
                G.del_var(git, var)
            notes.append(f"group random{n} is no longer replaced by the camp: its spawn script is "
                         + (f"restored to {chain!r}" if chain else "cleared again"))
    return notes


def wire_gate(git: dict, read_script: Callable[[str], Optional[str]], plan_id: str, gate: str, group: int) -> str:
    """Point `random<group>_spawn_script` at our gate and return the script it must chain to ("" for none)."""
    if not G.get_var(git, f"random{group}"):
        raise CampEventError(f"camp_event.replaces_group = {group}: this area has no spawn group random{group}")
    var = f"random{group}_spawn_script"
    cur = G.get_var(git, var) or ""
    if cur == gate:
        chain = chain_of(read_script(gate))
    else:
        owner = generated_by(read_script(cur)) if cur else None
        if owner is not None and owner[0] == "gate":
            raise CampEventError(f"group random{group} is already replaced by the camp of plan {owner[1]!r} (its gate is {cur!r}): "
                                 "one camp per group")
        chain = cur
    G.set_var(git, var, gate)
    return chain


def effective_chance(git: dict, ours: int) -> tuple[int, bool, int, float]:
    """(event_chance in effect, whether that is the TFN default, contiguous event slots, chance per refresh that our camp is the one)."""
    raw = G.vars_of(git).get("event_chance")
    explicit = isinstance(raw, int) and raw > 0
    chance = raw if explicit else DEFAULT_EVENT_CHANCE
    total = len(event_run(git))
    waypoints = len(event_waypoints(git))
    p = (chance / 100.0) * (ours / total if total else 0.0) if waypoints else 0.0
    return chance, not explicit, total, p


def apply_wiring(git: dict, read_script: Callable[[str], Optional[str]], plan_id: str, ce: Optional[dict]) -> Wiring:
    """Wire the area for the plan's camp event (or unwire it when `ce` is None). Mutates `git`; scripts are saved by the caller."""
    script = ce["script"] if ce else None
    gate = (ce["gate"], ce["replaces_group"]) if ce and ce["replaces_group"] else None
    w = Wiring(script=script or "")
    w.notes.extend(release_stale(git, read_script, plan_id, script, gate))
    if ce is None:
        return w
    run = plan_event_run(event_run(git), script, ce["weight"])
    if len(run) > MAX_EVENT_SLOTS:
        raise CampEventError(f"not enough free event slots: this area already has {len(run) - ce['weight']} other event(s) and the "
                             f"camp needs {ce['weight']} (area_init counts at most {MAX_EVENT_SLOTS})")
    w.warnings.extend(write_event_run(git, run))
    w.slots = [n for n, name in enumerate(event_run(git), 1) if name == script]
    w.other_events = [name for name in event_run(git) if name != script]
    if gate:
        chain = wire_gate(git, read_script, plan_id, gate[0], gate[1])
        w.gate = {"script": gate[0], "group": gate[1], "chain": chain, "radius": ce["replace_radius"]}
    w.event_chance, w.chance_is_default, w.slots_total, w.effective = effective_chance(git, len(w.slots))
    w.event_waypoints = len(event_waypoints(git))
    return w


