def centroid(objs: list[dict]) -> tuple[float, float]:
    return (sum(o["x"] for o in objs) / len(objs), sum(o["y"] for o in objs) / len(objs))


def default_origin(objs: list[dict]) -> dict:
    cx, cy = centroid(objs)
    return {"x": round(cx, 4), "y": round(cy, 4), "facing": DEFAULT_FACING}


def footprint_radius(objs: list[dict], origin: dict) -> float:
    """Distance from the pivot to the farthest template object."""
    return max((math.hypot(o["x"] - origin["x"], o["y"] - origin["y"]) for o in objs), default=0.0)


def candidates(ce: dict, origin: dict) -> list[dict]:
    """Where the camp may appear: the spots, plus the design location when asked (or when there are no spots)."""
    out: list[dict] = []
    if not ce["spots"] or ce["include_origin"]:
        out.append({"x": origin["x"], "y": origin["y"], "facing": origin["facing"], "label": "design location", "origin": True})
    for i, s in enumerate(ce["spots"]):
        out.append({"x": s["x"], "y": s["y"], "facing": s["facing"], "label": f"spot {i + 1}", "origin": False})
    return out


def transform(x: float, y: float, facing: float, origin: dict, cand: dict) -> tuple[float, float, float]:
    """Move a template object so the pivot lands on `cand`, rotating CCW by cand.facing - origin.facing (like prefab stamping)."""
    theta = cand["facing"] - origin["facing"]
    rad = math.radians(theta)
    c, s = math.cos(rad), math.sin(rad)
    dx, dy = x - origin["x"], y - origin["y"]
    return (cand["x"] + dx * c - dy * s, cand["y"] + dx * s + dy * c, (facing + theta) % 360)


@dataclass
class Ground:
    """What the studio knows about the ground at a point (walkmesh exact, or guessed from neighbours)."""
    z: float
    how: str                      # "walkmesh" | "near" | "flat" | "area_median" | "default"
    walkable: Optional[bool]      # None when there is no walkmesh to ask
    label: str = ""


@dataclass
class VObj:
    kind: str                     # placeable | creature
    resref: str
    x: float
    y: float
    z: float
    facing: float
    tag: str = ""
    walkable: Optional[bool] = None
    quest_npc: bool = False       # creature carries a `quest1` variable: area_refresh puts such NPCs on the area's quest list

    def to_dict(self) -> dict:
        return {"kind": self.kind, "resref": self.resref, "x": self.x, "y": self.y, "z": self.z, "facing": self.facing,
                "walkable": self.walkable}


@dataclass
class Variant:
    label: str
    x: float
    y: float
    z: float
    facing: float
    objects: list[VObj] = field(default_factory=list)
    issues: list[tuple[str, str]] = field(default_factory=list)      # (level, message)
    z_how: str = ""

    @property
    def errors(self) -> list[str]:
        return [m for lvl, m in self.issues if lvl == "error"]

    def to_dict(self) -> dict:
        return {"label": self.label, "x": self.x, "y": self.y, "z": self.z, "facing": self.facing, "z_how": self.z_how,
                "objects": [o.to_dict() for o in self.objects],
                "issues": [{"level": lvl, "message": m} for lvl, m in self.issues]}


def build_variants(objs: list[dict], origin: dict, cands: list[dict], ground: Callable[[float, float], Ground],
                   in_bounds: Callable[[float, float], bool], existing: list[tuple[float, float]],
                   min_spacing: float) -> list[Variant]:
    """One variant per candidate: every template object moved/rotated/grounded, with per-spot problems collected (never raised).

    Template objects are dicts {kind, resref, x, y, z (None = ground), dz (height above ground for an explicit z), facing, tag,
    quest_npc}.  An explicit z is kept as typed at the design location and kept as "height above the ground" everywhere else.
    Ground heights come from the walkmesh per object; where there is none every object of the camp takes the spot's own height.
    """
    variants: list[Variant] = []
    for cand in cands:
        gc = ground(cand["x"], cand["y"])
        var = Variant(cand["label"], round(cand["x"], 4), round(cand["y"], 4), I.snap(gc.z), round(cand["facing"], 2),
                      z_how=gc.how)
        if not in_bounds(cand["x"], cand["y"]):
            var.issues.append(("error", f"{cand['label']} at ({cand['x']:.1f}, {cand['y']:.1f}) is outside the area"))
        if gc.walkable is False:
            var.issues.append(("warning", f"{cand['label']} itself is on non-walkable ground ({gc.label or 'no walkmesh face'})"))
        identity = (abs(cand["facing"] - origin["facing"]) < 1e-9 and abs(cand["x"] - origin["x"]) < 1e-9
                    and abs(cand["y"] - origin["y"]) < 1e-9)
        creatures_off = 0
        props_off: dict[str, int] = {}
        outside: list[str] = []
        crowded = 0
        for o in objs:
            nx, ny, nf = transform(o["x"], o["y"], o["facing"], origin, cand)
            if not in_bounds(nx, ny):
                outside.append(f"{o['resref']} ({nx:.1f}, {ny:.1f})")
                continue
            g = ground(nx, ny)
            base = g.z if g.how == "walkmesh" else gc.z      # a guess per object would scatter a camp over mixed heights
            if o["z"] is None:
                z = base
            elif identity:
                z = o["z"]
            else:
                z = base + o.get("dz", 0.0)
            if g.walkable is False:
                if o["kind"] == "creature":
                    creatures_off += 1
                else:
                    key = g.label or "no walkmesh face"
                    props_off[key] = props_off.get(key, 0) + 1
            if any(math.hypot(ex - nx, ey - ny) < min_spacing for ex, ey in existing):
                crowded += 1
            var.objects.append(VObj(o["kind"], o["resref"], round(nx, 4), round(ny, 4), I.snap(z), round(nf, 2),
                                    o.get("tag", ""), g.walkable, bool(o.get("quest_npc"))))
        if outside:
            shown = ", ".join(outside[:3]) + (f" and {len(outside) - 3} more" if len(outside) > 3 else "")
            var.issues.append(("error", f"{cand['label']}: {len(outside)} object(s) would fall outside the area ({shown}) - move the spot inwards"))
        if creatures_off:
            var.issues.append(("warning", f"{cand['label']}: {creatures_off} creature(s) would stand on non-walkable ground and may be stuck"))
        if props_off:
            var.issues.append(("info", f"{cand['label']}: props on non-walkable surfaces (fine for rocks/trees/walls): "
                               + ", ".join(f"{n}x {k}" for k, n in props_off.items())))
        if crowded:
            var.issues.append(("warning", f"{cand['label']}: {crowded} object(s) would be within {min_spacing:g} m of an existing object"))
        variants.append(var)
    for i, a in enumerate(variants):
        for b in variants[i + 1:]:
            if math.hypot(a.x - b.x, a.y - b.y) < SPOT_SPACING_WARN and abs((a.facing - b.facing + 180) % 360 - 180) < 1:
                b.issues.append(("warning", f"{b.label} is almost identical to {a.label}: the camp would appear in the same place twice"))
    return variants


