def _f(v: float) -> str:
    return f"{I.snap(v, 4):.4f}"


def _nwstr(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "").replace("\t", " ")
    return '"' + out + '"'


