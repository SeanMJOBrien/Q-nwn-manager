"""Random camp events: a camp that appears only sometimes, at one of several hand-placed spots, when an area refreshes.

TFN's event system (SPAWN_SYSTEM.md section 4, area_refresh.nss): `_wp_event` waypoints + area vars `eventN` (script names) +
`event_chance`; per refresh one roll, then ONE random `eventN` script runs with OBJECT_SELF = a random event waypoint.  A camp
plan with a `camp_event` block turns its creatures and placeables into a *template*: they are not written to the GIT but compiled
into a generated event script that creates them at runtime.  Each *spot* (position + direction) says where the template may
appear: the template is rotated about its pivot by `spot.facing - origin.facing` and the pivot is moved to the spot.  Every
variant is computed here, at stage time, so each spot is checked against the walkmesh (exact Z, walkability, bounds) and can be
previewed on the map; the script only holds absolute numbers.

Optionally the camp REPLACES a spawn group: a generated gate script (`randomN_spawn_script`) removes that group's creatures (all
of them, or those within a radius of the camp) while the camp stands, chaining to the group's own spawn script if it has one.

Two TFN facts shape the wiring (both verified in area_init.nss / area_refresh.nss):
  * `events` is counted from event1 upwards and stops at the FIRST EMPTY slot, so the slots must stay contiguous;
  * one event is picked with Random(events) after a single `event_chance` roll (0 or unset means 50), and only when the area has
    at least one `_wp_event` waypoint.

Ownership: generated scripts start with `// tfn-studio camp event|gate: plan <id>`; only scripts with the same plan id are ever
overwritten, so TFN's own scripts can never be clobbered.  See PLAN.md section 4b for the design decisions.
"""

