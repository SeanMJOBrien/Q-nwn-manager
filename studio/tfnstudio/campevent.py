def event_script_source(plan_id: str, title: str, area: str, variants: list[Variant], *, tag: str,
                        marker: str = MARKER_BLUEPRINT) -> str:
    """The generated event script: one function per spot and a main() that builds one at random."""
    has_props = any(o.kind == "placeable" for v in variants for o in v.objects)
    has_quest = any(o.quest_npc for v in variants for o in v.objects)
    lines = [
        f"// Random camp: {comment_text(title)} (plan {plan_id}) in area {area}.",
        f"// tfn-studio camp event: plan {plan_id}",
        "// Generated by tfn-studio. Do not edit by hand: change the plan in the Camp Builder and stage it again.",
        "// Runs from area_refresh as one of the area's eventN scripts (OBJECT_SELF = an event waypoint) and builds the camp",
        f"// at one of its {len(variants)} spot(s), chosen at random. Everything it creates is registered for the area cleanup.",
        '#include "inc_area"',
    ]
    if has_props:
        lines.append('#include "nwnx_object"')
    if has_quest:
        lines.append('#include "nwnx_creature"')
    lines += ["", f"const string CAMP_TAG = {_nwstr(tag)};", "",
              "object CampCreate(int nType, object oArea, string sResRef, float fX, float fY, float fZ, float fFacing, string sTag = \"\")",
              "{",
              "    object oObj = CreateObject(nType, sResRef, Location(oArea, Vector(fX, fY, fZ), fFacing), FALSE, sTag);",
              "    AddObjectToAreaCleanupList(oArea, oObj);",
              "    return oObj;",
              "}", ""]
    if has_props:
        lines += [_FINISH_PROP]
    if has_quest:
        lines += [_QUEST_NPC]
    for n, v in enumerate(variants, 1):
        lines.append(f"// {v.label}: pivot at ({_f(v.x)}, {_f(v.y)}) facing {_f(v.facing)}, {len(v.objects)} object(s)")
        lines.append(f"void CampSpot{n}(object oArea)")
        lines.append("{")
        lines.append('    // the marker means "the camp is standing": the gate script and the re-entry guard look for its tag')
        lines.append(f"    CampCreate(OBJECT_TYPE_WAYPOINT, oArea, {_nwstr(marker)}, {_f(v.x)}, {_f(v.y)}, {_f(v.z)}, {_f(v.facing)}, CAMP_TAG);")
        for o in sorted(v.objects, key=lambda obj: 0 if obj.kind == "placeable" else 1):
            const = "OBJECT_TYPE_PLACEABLE" if o.kind == "placeable" else "OBJECT_TYPE_CREATURE"
            args = f"{const}, oArea, {_nwstr(o.resref)}, {_f(o.x)}, {_f(o.y)}, {_f(o.z)}, {_f(o.facing)}"
            if o.tag:
                args += f", {_nwstr(o.tag)}"
            if o.kind == "placeable":
                lines.append(f"    CampFinishProp(CampCreate({args}));")
            elif o.quest_npc:
                lines.append(f"    CampQuestNpc(oArea, CampCreate({args}));")
            else:
                lines.append(f"    CampCreate({args});")
        lines += ["}", ""]
    lines += ["void main()", "{",
              "    object oArea = GetArea(OBJECT_SELF);",
              f"    if (GetResRef(oArea) != {_nwstr(area)}) return;            // the numbers below belong to this area only",
              "    if (GetIsObjectValid(GetObjectByTag(CAMP_TAG))) return;      // already standing"]
    if len(variants) == 1:
        lines.append("    CampSpot1(oArea);")
    else:
        lines.append(f"    switch (Random({len(variants)}))")
        lines.append("    {")
        for n in range(1, len(variants) + 1):
            lines.append(f"        case {n - 1}: CampSpot{n}(oArea); break;")
        lines.append("    }")
    lines += ["}", ""]
    return "\n".join(lines)


def gate_script_source(plan_id: str, area: str, group: int, radius: float, chain: str, *, tag: str) -> str:
    """The `randomN_spawn_script` gate: while the camp stands, remove the group's creatures (all, or those near the camp)."""
    near = "all of its creatures" if radius <= 0 else f"its creatures within {radius:g} m of the camp"
    lines = [
        f"// Gate for spawn group random{group} in area {area}: while the camp of plan {plan_id} stands it replaces {near}.",
        f"// tfn-studio camp gate: plan {plan_id}",
        f"// tfn-studio chains: {chain or '-'}",
        "// Generated by tfn-studio. Do not edit by hand: change the plan in the Camp Builder and stage it again.",
        "// area_refresh runs this on every creature of the group right after it spawns (OBJECT_SELF = the creature).",
        "void main()",
        "{",
        f"    object oCamp = GetObjectByTag({_nwstr(tag)});",
        "    if (GetIsObjectValid(oCamp))",
        "    {",
    ]
    if radius <= 0:
        lines += ["        DestroyObject(OBJECT_SELF);", "        return;"]
    else:
        lines += ["        float fDist = GetDistanceBetween(OBJECT_SELF, oCamp);",
                  f"        if (fDist >= 0.0 && fDist <= {_f(radius)})",
                  "        {",
                  "            DestroyObject(OBJECT_SELF);",
                  "            return;",
                  "        }"]
    lines.append("    }")
    if chain:
        lines.append(f"    ExecuteScript({_nwstr(chain)}, OBJECT_SELF);          // the group's own spawn script")
    lines += ["}", ""]
    return "\n".join(lines)


