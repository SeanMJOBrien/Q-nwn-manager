import { $, h, api, clear, navbar, toast, modal, issueList, issueCounts, diffView, fmtTime, put } from '/static/common.js';

const app = $('#app');
let changes = [];
let currentId = location.hash.slice(1) || null;
let issues = null;

function layout() {
  clear(app);
  app.className = 'full';
  put(app, h('div', { class: 'pane-left', id: 'list' }), h('div', { class: 'pane-center', style: { padding: '16px', overflow: 'auto' }, id: 'detail' }));
}

async function loadList() {
  changes = await api('/api/changes');
  const box = $('#list');
  clear(box);
  put(box, h('h2', {}, 'Change sets'),
    h('p', { class: 'muted small' }, 'Generated by the builders. Nothing is written to TFN until you press Apply.'));
  if (!changes.length) put(box, h('p', { class: 'muted' }, 'No change sets yet.'));
  for (const c of changes) {
    put(box, h('div', { class: `card${c.id === currentId ? ' sel' : ''}`, style: { cursor: 'pointer', borderColor: c.id === currentId ? 'var(--accent)' : '' },
      onclick: () => select(c.id) },
      h('div', { class: 'row' }, h('b', {}, c.title), c.applied ? h('span', { class: 'chip good right' }, 'applied') : h('span', { class: 'chip warn right' }, 'staged')),
      h('div', { class: 'muted small' }, `${c.kind} · ${c.files} file(s) · ${fmtTimeShort(c.created)}`)));
  }
}

function fmtTimeShort(sec) { return sec ? new Date(sec * 1000).toLocaleString([], { dateStyle: 'short', timeStyle: 'short' }) : ''; }

async function select(id) {
  currentId = id;
  location.hash = id;
  issues = null;
  await loadList();
  await showDetail();
}

async function showDetail() {
  const box = $('#detail');
  clear(box);
  if (!currentId) { put(box, h('p', { class: 'muted' }, 'Select a change set on the left.')); return; }
  let s;
  try { s = await api(`/api/changes/${currentId}`); }
  catch (e) { put(box, h('div', { class: 'card' }, `Cannot load ${currentId}: ${e.message}`)); return; }
  const entry = changes.find(c => c.id === currentId) || {};
  const applied = !!entry.applied;
  const issuesBox = h('div', {}, h('p', { class: 'muted' }, 'Validating…'));
  const filesBox = h('div', {});

  const actions = h('div', { class: 'row' },
    h('button', { onclick: () => runValidate(issuesBox, true) }, 'Re-validate'),
    applied ? h('button', { class: 'danger', onclick: () => doUndo() }, 'Undo apply')
            : h('button', { class: 'primary', id: 'applyBtn', onclick: () => doApply(s) }, 'Apply to TFN…'),
    h('button', { class: 'danger right', onclick: () => doDiscard() }, 'Discard'));

  put(box, h('h1', {}, s.title),
    h('div', { class: 'row muted' }, h('span', { class: 'chip' }, s.kind), h('span', { class: 'mono small' }, s.id),
      s.spec ? h('span', { class: 'small' }, `spec: ${s.spec}`) : null),
    h('div', { style: { margin: '12px 0' } }, actions),
    h('div', { class: 'card' }, h('h2', {}, 'Files'),
      h('table', {}, h('thead', {}, h('tr', {}, ['', 'File', 'Change', 'Note'].map(t => h('th', {}, t)))),
        h('tbody', {}, s.files.map(f => h('tr', { class: 'clickable', onclick: () => toggleDiff(f.rel, filesBox) },
          h('td', {}, f.action === 'create' ? h('span', { class: 'chip good' }, 'new') : h('span', { class: 'chip' }, 'edit')),
          h('td', { class: 'mono' }, f.rel),
          h('td', {}, f.changed ? h('span', {}, h('span', { style: { color: 'var(--good)' } }, `+${f.added}`), ' ', h('span', { style: { color: 'var(--bad)' } }, `-${f.removed}`)) : h('span', { class: 'muted' }, 'no change')),
          h('td', { class: 'muted' }, f.note))))),
      h('p', { class: 'muted small' }, 'Click a file to see its diff.'), filesBox),
    s.notes.length ? h('div', { class: 'card' }, h('h2', {}, 'Notes'), h('ul', { style: { margin: 0, paddingLeft: '18px' } }, s.notes.map(n => h('li', {}, n)))) : null,
    h('div', { class: 'card' }, h('h2', {}, 'Validation'), issuesBox));
  runValidate(issuesBox, false);
}

async function runValidate(box, announce) {
  clear(box);
  put(box, h('p', { class: 'muted' }, 'Validating (JSON round trip through nwn_gff, lints, script compile)…'));
  try {
    const r = await api(`/api/changes/${currentId}/validate`, { method: 'POST', body: {} });
    issues = r.issues;
    const c = issueCounts(issues);
    clear(box);
    put(box, h('div', { class: 'row' },
      c.error ? h('span', { class: 'badge error' }, `${c.error} errors`) : h('span', { class: 'badge good' }, '0 errors'),
      h('span', { class: 'badge warning' }, `${c.warning} warnings`), h('span', { class: 'muted small' }, `${c.info} info`)),
      issueList(issues));
    const btn = $('#applyBtn');
    if (btn) btn.title = c.error ? 'Validation has errors; Apply will refuse unless forced' : '';
    if (announce) toast(c.error ? 'Validation found errors' : 'Validation passed', c.error ? 'error' : 'good');
  } catch (e) { clear(box); put(box, h('div', { class: 'issue error' }, e.message)); }
}

async function toggleDiff(rel, host) {
  if (host.dataset.rel === rel && host.firstChild) { clear(host); host.dataset.rel = ''; return; }
  host.dataset.rel = rel;
  clear(host);
  put(host, h('p', { class: 'muted' }, 'Loading diff…'));
  try {
    const d = await api(`/api/changes/${currentId}/diff?file=${encodeURIComponent(rel)}`);
    clear(host);
    put(host, h('div', { class: 'mono small muted' }, rel), diffView(d.diff));
    if (d.truncated) put(host, h('p', { class: 'muted small' }, `Diff truncated (${d.size} chars total).`));
  } catch (e) { clear(host); put(host, h('div', { class: 'issue error' }, e.message)); }
}

async function doApply(s) {
  const errs = issues ? issues.filter(i => i.level === 'error').length : 0;
  const body = h('div', {},
    h('p', {}, `This writes ${s.files.filter(f => f.changed).length} file(s) into the TFN source tree:`),
    h('ul', {}, s.files.filter(f => f.changed).map(f => h('li', { class: 'mono' }, f.rel))),
    errs ? h('div', { class: 'issue error' }, `Validation reported ${errs} error(s). Apply will be refused unless you force it.`) : null,
    h('p', { class: 'muted small' }, 'Apply refuses files with uncommitted git changes and files changed since staging. An undo record is kept.'));
  const ok = await modal('Apply to TFN', body, [{ label: 'Cancel', value: false }, { label: 'Apply', value: true, primary: true }]);
  if (!ok) return;
  let r = await api(`/api/changes/${currentId}/apply`, { method: 'POST', body: {} });
  if (!r.ok && r.problems && r.problems.some(p => p.includes('uncommitted'))) {
    const again = await modal('Files have uncommitted changes', h('div', {},
      h('ul', {}, r.problems.map(p => h('li', {}, p))),
      h('p', {}, 'Applying anyway mixes generated edits with your uncommitted work in those files.')),
      [{ label: 'Cancel', value: false }, { label: 'Apply anyway', value: true, danger: true }]);
    if (again) r = await api(`/api/changes/${currentId}/apply`, { method: 'POST', body: { allow_dirty: true } });
  }
  if (r.ok) { toast(`Applied ${r.applied.length} file(s). Build, then restart the server.`, 'good', 8000); }
  else toast((r.problems || ['Apply failed']).join('; '), 'error');
  await select(currentId);
}

async function doUndo() {
  if (!(await modal('Undo apply', h('p', {}, 'Restore the files exactly as they were before this change set was applied?'),
    [{ label: 'Cancel', value: false }, { label: 'Undo', value: true, danger: true }]))) return;
  const r = await api(`/api/changes/${currentId}/undo`, { method: 'POST', body: {} });
  if (r.ok) toast('Restored previous files', 'good'); else toast(r.problems.join('; '), 'error');
  await select(currentId);
}

async function doDiscard() {
  if (!(await modal('Discard change set', h('p', {}, 'Delete this staged change set? Applied files are not touched.'),
    [{ label: 'Cancel', value: false }, { label: 'Discard', value: true, danger: true }]))) return;
  await api(`/api/changes/${currentId}/discard`, { method: 'POST', body: {} });
  currentId = null; location.hash = '';
  await loadList(); await showDetail();
}

await navbar('/changes');
layout();
await loadList();
await showDetail();
window.addEventListener('hashchange', () => { const id = location.hash.slice(1); if (id && id !== currentId) select(id); });
