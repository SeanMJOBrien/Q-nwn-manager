@dataclass
class Participant:
    resref: str
    mode: str                       # new | existing
    bp: dict
    stages: list[dict] = field(default_factory=list)   # talk stages handled here
    slots: dict[int, int] = field(default_factory=dict)  # stage n -> slot
    spec: dict = field(default_factory=dict)


class QuestBuilder:
    def __init__(self, project: TfnProject, walk=None):
        self.p = project
        self.generic = project.profile == "generic"
        self.walk = walk if (walk is not None and walk.available()) else None
        self.areas: dict[str, dict] = {}
        self.report: dict[str, Any] = {}
        self._places: list[tuple[str, dict, str]] = []

    # -------------------------------------------------------------- utilities
    def _refresh_index(self) -> None:
        self.areas = IX.area_index(self.p)

    def _exists(self, cs: ChangeSet, ext: str, res: str) -> bool:
        return cs.exists(ext, res)

    def _areas_with_creature(self, resref: str) -> list[str]:
        return sorted(a["resref"] for a in self.areas.values() if (a.get("cre") or {}).get(resref))

    def _instance_vars(self, cs: ChangeSet, resref: str) -> list[dict]:
        """VarTables of every placed instance of `resref` (they snapshot the blueprint's vars)."""
        out: list[dict] = []
        for area in self._areas_with_creature(resref):
            git = cs.load("git", area)
            out += [G.vars_of(i) for i in I.instances(git, "creature") if G.get(i, "TemplateResRef") == resref]
        return out

    def _patch_instances(self, cs: ChangeSet, resref: str, fn) -> int:
        """Apply fn(instance) to every placed creature instance of `resref` (stale-snapshot fix)."""
        n = 0
        for area in self._areas_with_creature(resref):
            git = cs.load("git", area)
            touched = False
            for inst in I.instances(git, "creature"):
                if G.get(inst, "TemplateResRef") == resref:
                    fn(inst)
                    touched = True
                    n += 1
            if touched:
                cs.save("git", area, git, note=f"quest vars on placed {resref}")
        return n

    def _defer_place(self, resref: str, place: dict, what: str) -> None:
        """Placement happens last so the instance snapshots the *final* blueprint."""
        self._places.append((resref, place, what))

    def _flush_places(self, cs: ChangeSet, plan: str) -> None:
        for res, place, what in self._places:
            area = str(place.get("area", ""))
            if not self._exists(cs, "are", area) or not self._exists(cs, "git", area):
                raise QuestError(f"{what}: placement area {area!r} not found")
            are = cs.load("are", area)
            x, y = float(place["x"]), float(place["y"])
            if not I.in_bounds(are, x, y, margin=0.5):
                raise QuestError(f"{what}: ({x:.1f}, {y:.1f}) is outside area {area}")
            git = cs.load("git", area)
            z = place.get("z")
            probe = None
            if self.walk is not None:
                self.walk.prepare(are)
                probe = self.walk.probe(are, x, y)
                if probe.walkable and z is None and probe.z is not None:
                    z = I.snap(probe.z)
                if not probe.walkable:
                    cs.warnings.append(f"{what} at ({x:.1f}, {y:.1f}) in {area} is on non-walkable ground "
                                       f"({probe.label or probe.error}): it may be stuck or unreachable")
            if z is None:
                z, _ = I.infer_z(git, x, y)
            inst = I.creature_instance(cs.load("utc", res), x, y, float(z), float(place.get("facing", 90)), plan=plan)
            I.add_instance(git, "creature", inst)
            cs.save("git", area, git, note=f"{what} placed by quest plan")
            cs.notes.append(f"{what} placed in {area} at ({x:.1f}, {y:.1f})")
        self._places = []

    def _clean_plan(self, cs: ChangeSet, plan: str) -> None:
        for a in self.areas.values():
            if plan in (a.get("plans") or []):
                git = cs.load("git", a["resref"])
                if I.remove_plan_instances(git, plan):
                    cs.save("git", a["resref"], git, note=f"removed previous {plan} placements")

    # ------------------------------------------------------------- blueprints
    def _clone_creature(self, cs: ChangeSet, spec: dict, tag: str, what: str, conversation: str = "",
                        plot: bool | None = None) -> dict:
        """New creature blueprint cloned from `clone_from`, or the one this tool generated earlier."""
        res = check_new_resref(spec["resref"], f"{what} resref")
        if self._exists(cs, "utc", res):
            bp = cs.load("utc", res)
            if not str(G.get(bp, "Comment", "")).startswith(MARK):
                raise QuestError(f"{what}: creature blueprint {res!r} already exists and was not generated by this "
                                 "tool; pick another resref or use mode `existing`")
        else:
            base = spec.get("clone_from")
            if not base or not self._exists(cs, "utc", base):
                raise QuestError(f"{what}: `clone_from` must name an existing creature blueprint (got {base!r})")
            bp = cs.load("utc", base)
            strip_all_quest_vars(bp)  # inherited wiring belongs to the other quest
        name = _txt(spec, "name") or res
        bp["TemplateResRef"] = G.resref(res)
        bp["Tag"] = G.cexostring(res)
        bp["FirstName"] = _locname(name)
        bp["LastName"] = _locname("")
        if spec.get("description"):
            bp["Description"] = _locname(str(spec["description"]))
        bp["Comment"] = G.cexostring(f"{MARK}: quest {tag}")
        if conversation:
            bp["Conversation"] = G.resref(conversation)
        if plot is not None:
            bp["Plot"] = G.byte(1 if plot else 0)
        return bp

    # --------------------------------------------------------------- build
    def build(self, spec_in: dict, cs: ChangeSet | None = None) -> tuple[ChangeSet, dict]:
        spec = normalize(spec_in)
        tag = spec["tag"]
        if self.generic:
            spec["script_style"] = "modern"     # the older numbered scripts only exist in The Frozen North
        self._refresh_index()
        self._places = []
        cs = cs or ChangeSet(self.p, f"Quest {tag}", "quest", spec=f"specs/quests/{tag}.json")
        report: dict[str, Any] = {"tag": tag, "journal": {}, "participants": [], "targets": [], "items": [],
                                  "explore": [], "dialogs": []}
        plan = f"quest_{tag}"
        self._clean_plan(cs, plan)
        if self.generic:
            RT.ensure(self.p, cs)
            foreign = RT.status(self.p)["foreign"]
            if foreign:
                raise QuestError("this module already has scripts named like the studio's quest runtime ("
                                 + ", ".join(foreign) + "): rename them or write the quest scripts by hand")

        stages = spec["stages"]
        last_n = stages[-1]["n"]

        # ---- journal ---------------------------------------------------------
        self._journal(cs, spec, report)

        # ---- participants (talk stages) ---------------------------------------
        giver_spec = spec["giver"]
        parts: dict[str, Participant] = {}
        for st in stages:
            if st["via"] != "talk":
                continue
            npc = st.get("npc") or {}
            res = npc.get("resref") or giver_spec["resref"]
            if res not in parts:
                if res == giver_spec["resref"]:
                    parts[res] = self._make_participant(cs, giver_spec, tag)
                else:
                    parts[res] = self._make_participant(cs, {"mode": "existing", **npc, "resref": res}, tag)
            parts[res].stages.append(st)

        for part in parts.values():
            self._wire_participant(cs, spec, part, last_n, report)

        # ---- other mechanisms ---------------------------------------------------
        for st in stages:
            if st["via"] == "kill":
                self._wire_kill(cs, spec, st, report)
        for st in stages:
            if st["via"] == "pickup":
                self._wire_pickup(cs, spec, st, report)
            elif st["via"] == "explore":
                self._wire_explore(cs, spec, st, report)

        self._flush_places(cs, plan)
        self._notes(cs, spec)
        if self.generic:
            cs.notes.append("Rebuild the module (`nwn-manager repack`) and test: talk to the giver, check the journal after "
                            "each stage. Quest progress is stored on the player character.")
        else:
            cs.notes.append("Restart the server after applying: area_init registers quest NPCs at module load. "
                            "No reseed is needed (SEED_SYSTEM.md section 12).")
        self.report = report
        return cs, report

    # ------------------------------------------------------------- journal
    def _journal(self, cs: ChangeSet, spec: dict, report: dict) -> None:
        tag = spec["tag"]
        # a fresh module has no journal file until its first quest
        jrl = cs.load("jrl", "module") if cs.exists("jrl", "module") else {"__data_type": "JRL ", "Categories": G.list_()}
        cats = jrl["Categories"]["value"]
        entries = []
        stages = spec["stages"]
        for i, st in enumerate(stages):
            end = 1 if (st["n"] == stages[-1]["n"]) else 0
            entries.append(G.struct(i, End=G.word(end), ID=G.dword(st["n"]), Text=G.locstring(st["journal"])))
        existing = next((i for i, c in enumerate(cats) if G.get(c, "Tag") == tag), None)
        sid = existing if existing is not None else len(cats)
        cat = G.struct(sid, Comment=G.cexostring(MARK), EntryList=G.list_(entries), Name=G.locstring(spec["name"]),
                       Picture=G.word(65535), Priority=G.dword(spec["priority"]), Tag=G.cexostring(tag),
                       XP=G.dword(0))
        if existing is not None:
            if G.get(cats[existing], "Comment", "") != MARK:
                raise QuestError(f"journal tag {tag!r} already exists and was not generated by this tool; "
                                 "pick another tag")
            if cats[existing] != cat:
                cs.notes.append(f"journal category {tag} replaced")
            cats[existing] = cat
        else:
            cats.append(cat)
        cs.save("jrl", "module", jrl, note=f"journal category {tag}")
        report["journal"] = {"tag": tag, "name": spec["name"], "stages": [s["n"] for s in stages]}

    # --------------------------------------------------------- participants
    def _make_participant(self, cs: ChangeSet, pspec: dict, tag: str) -> Participant:
        res = pspec["resref"]
        mode = pspec.get("mode", "new")
        if mode == "existing":
            if not self._exists(cs, "utc", res):
                raise QuestError(f"NPC blueprint {res!r} not found in src/utc")
            return Participant(res, "existing", cs.load("utc", res), spec=pspec)
        # new NPC: Conversation = same resref (TFN convention); Plot so they are unkillable & highlighted
        bp = self._clone_creature(cs, pspec, tag, "giver", conversation=res, plot=True)
        return Participant(res, "new", bp, spec=pspec)

    def _wire_participant(self, cs: ChangeSet, spec: dict, part: Participant, last_n: int, report: dict) -> None:
        tag = spec["tag"]
        res = part.resref
        inst_vars = self._instance_vars(cs, res) if part.mode == "existing" else []
        part.slots = pick_slots(G.vars_of(part.bp), inst_vars, tag, [st["n"] for st in part.stages])
        wanted: dict[str, Any] = {}
        for st in part.stages:
            wanted.update(stage_vars(tag, st, part.slots[st["n"]]))
        sync_vars(part.bp, tag, wanted)

        # dialog -----------------------------------------------------------------
        conv = G.get(part.bp, "Conversation", "")
        dlg_res = conv or res
        if not conv:
            part.bp["Conversation"] = G.resref(dlg_res)
        merge_into = self._exists(cs, "dlg", dlg_res)
        dlg = cs.load("dlg", dlg_res) if merge_into else None
        if merge_into and part.mode == "new":
            if not any(G.get(n, "Comment", "").startswith("studio:") for n in dlg["EntryList"]["value"]):
                raise QuestError(f"dialog {dlg_res!r} already exists and was not generated by this tool")
        b = D.DialogBuilder(dlg)
        b.remove_generated(f"studio:{tag}:")
        self._dialog_nodes(cs, b, spec, part, last_n)
        cs.save("dlg", dlg_res, b.finish(), note=f"quest dialog for {res}")
        if merge_into and part.mode == "existing":
            sharers = [r for r, c in IX.creature_index(self.p).items() if c.get("conversation") == dlg_res and r != res]
            if sharers:
                cs.warnings.append(f"dialog {dlg_res!r} is shared with {len(sharers)} other creature(s) "
                                   f"({', '.join(sharers[:5])}); quest slot numbers in its conditions could "
                                   "collide with their own quest variables")

        # blueprint + placed instances ------------------------------------------------
        cs.save("utc", res, _sort_top(part.bp), note=f"{part.mode} NPC {res}")

        def patch(inst: dict) -> None:
            sync_vars(inst, tag, wanted)
            if not G.get(inst, "Conversation"):
                inst["Conversation"] = G.resref(dlg_res)

        patched = self._patch_instances(cs, res, patch) if part.mode == "existing" else 0
        if part.mode == "new":
            if part.spec.get("place"):
                self._defer_place(res, part.spec["place"], f"NPC {res}")
            else:
                cs.notes.append(f"NPC {res} was created but not placed: put it in an area (Camp Builder / toolset)")
        report["participants"].append({"resref": res, "mode": part.mode, "dialog": dlg_res,
                                       "slots": {str(n): s for n, s in part.slots.items()},
                                       "instances_patched": patched})
        report["dialogs"].append({"resref": dlg_res, "outline": D.flatten(b.d)})

        if part.mode == "existing":
            fac = G.get(part.bp, "FactionID")
            if not (G.get(part.bp, "Plot") or G.get(part.bp, "IsImmortal") or fac in (2, 3, 4)):
                cs.warnings.append(f"NPC {res} is not plot/immortal nor commoner/merchant/defender: "
                                   "it will not get the yellow quest-giver highlight")

    def _cond_current(self, cs: ChangeSet, spec: dict, slot: int, tag: str, stage: int) -> tuple[str, dict | None]:
        """The "PC is currently at this stage" condition for quest slot `slot`.

        modern: one generic script, `dlg_q_chk_at`, told the slot through its `target` parameter (any slot).
        legacy: TFN's slot-numbered `dlg_q_chk_atc1..9`, else `dlg_q_chk_multi` for higher slots.
        """
        if spec.get("script_style") == "modern":
            if not self.p.script_exists(GENERIC_AT) and cs.pending_text(cs.rel_nss(GENERIC_AT)) is None:
                cs.save_nss(GENERIC_AT, GENERIC_AT_SRC, note="generic 'currently at quest stage' check")
            return GENERIC_AT, {"target": str(slot)}
        script = f"dlg_q_chk_atc{slot}"
        if slot <= 9 and self.p.script_exists(script):
            return script, None
        return "dlg_q_chk_multi", {"quest": tag, "stages": str(stage)}

    def _dialog_nodes(self, cs: ChangeSet, b: D.DialogBuilder, spec: dict, part: Participant, last_n: int) -> None:
        """Add this participant's quest conversation to `b` (all nodes tagged `studio:<tag>:...`).

        StartingList order (first passing condition wins):  advance-entries (latest stage first),
        then "currently at stage" reminders/farewell, then the stage-1 offer, then (new NPCs) a greeting.
        """
        tag = spec["tag"]
        c = f"studio:{tag}:"
        mine = {st["n"] for st in part.stages}
        elig: list[tuple[int, str, dict | None]] = []
        cur: list[tuple[int, str, dict | None]] = []
        offer: tuple[int, str, dict | None] | None = None

        def leave(n: int, tail: str) -> int:
            return b.add_reply(D.LEAVE, comment=c + f"s{n}:{tail}")

        for st in part.stages:
            n, slot = st["n"], part.slots[st["n"]]
            if n == 1:
                e_offer = b.add_entry(_txt(st, "offer", "I could use some help."), comment=c + f"s{n}:offer")
                r_yes = b.add_reply(_txt(st, "accept_reply", "I'll help you."), comment=c + f"s{n}:yes")
                r_no = b.add_reply(_txt(st, "decline_reply", "Not right now."), comment=c + f"s{n}:no")
                e_acc = b.add_entry(_txt(st, "accept", "Thank you. Be careful out there."), script="dlg_q_adv",
                                    params={"target": str(slot)}, comment=c + f"s{n}:accept")
                e_dec = b.add_entry(_txt(st, "decline", "Perhaps another time."), comment=c + f"s{n}:decline")
                b.entry_to_reply(e_offer, r_yes)
                b.entry_to_reply(e_offer, r_no)
                b.reply_to_entry(r_yes, e_acc)
                b.reply_to_entry(r_no, e_dec)
                b.entry_to_reply(e_acc, leave(n, "leave_acc"))
                b.entry_to_reply(e_dec, leave(n, "leave_dec"))
                offer = (e_offer, "dlg_q_chk_eli", {"target": str(slot)})
            else:
                e_adv = b.add_entry(_txt(st, "text", "Well done."), script="dlg_q_adv",
                                    params={"target": str(slot)}, comment=c + f"s{n}:advance")
                if _txt(st, "reply"):  # a PC line with no linked entries ends the conversation
                    b.entry_to_reply(e_adv, b.add_reply(_txt(st, "reply"), comment=c + f"s{n}:reply"))
                else:
                    b.entry_to_reply(e_adv, leave(n, "leave_adv"))
                elig.append((e_adv, "dlg_q_chk_eli", {"target": str(slot)}))
            # "currently at this stage": farewell when it is the last stage, else a reminder
            if n == last_n:
                txt, tail = _txt(st, "done", "Thank you again for your help."), "done"
            elif (n + 1) not in mine:
                txt, tail = _txt(st, "reminder", "Have you finished yet? I'm counting on you."), "reminder"
            else:
                continue
            e_cur = b.add_entry(txt, comment=c + f"s{n}:{tail}")
            b.entry_to_reply(e_cur, leave(n, "leave_cur"))
            script, params = self._cond_current(cs, spec, slot, tag, n)
            cur.append((e_cur, script, params))
        ordered = list(reversed(elig)) + list(reversed(cur)) + ([offer] if offer else [])
        for entry, script, params in reversed(ordered):
            b.add_start(entry, active=script, params=params, front=True)
        if part.mode == "new" and not [s for s in b.starts if not G.get(s, "Active")]:
            e_g = b.add_entry(_txt(part.spec, "greeting", "Hello, traveler."), comment=c + "greeting")
            b.entry_to_reply(e_g, b.add_reply(D.LEAVE, comment=c + "greeting:leave"))
            b.add_start(e_g, front=False)

    # ----------------------------------------------------------------- kill
    def _wire_kill(self, cs: ChangeSet, spec: dict, st: dict, report: dict) -> None:
        tag = spec["tag"]
        t = dict(st.get("target") or {})
        if not t.get("resref"):
            raise QuestError(f"stage {st['n']}: kill stages need a `target` with a resref")
        res = t["resref"]
        mode = t.get("mode", "new")
        what = f"kill target {res}"
        if mode == "existing":
            if not self._exists(cs, "utc", res):
                raise QuestError(f"{what}: blueprint not found in src/utc")
            bp = cs.load("utc", res)
            n_inst = sum((a.get("cre") or {}).get(res, 0) for a in self.areas.values())
            in_utes = [u for u, d in IX.ute_index(self.p).items() if any(c["resref"] == res for c in d["creatures"])]
            if in_utes:
                cs.warnings.append(f"{what} is used by {len(in_utes)} encounter blueprint(s) "
                                   f"({', '.join(in_utes[:4])}): EVERY spawn of it will advance the quest. "
                                   "Use mode `new` for a dedicated boss.")
            if n_inst > 6:
                cs.warnings.append(f"{what} is placed {n_inst} times across TFN: each kill advances the quest")
        else:
            bp = self._clone_creature(cs, t, tag, what)
        inst_vars = self._instance_vars(cs, res) if mode == "existing" else []
        slot = pick_slots(G.vars_of(bp), inst_vars, tag, [st["n"]])[st["n"]]
        existing_kill = G.get_var(bp, "quest_kill")
        if existing_kill and existing_kill != slot:
            raise QuestError(f"{what}: already has quest_kill = {existing_kill} for another quest; a creature can "
                             "credit only one quest kill")
        wanted = stage_vars(tag, st, slot)
        wanted["quest_kill"] = slot
        if t.get("boss", True):
            wanted["boss"] = 1
        sync_vars(bp, tag, wanted)
        script_death = G.get(bp, "ScriptDeath", "")
        if self.generic:
            if script_death in ("", "nw_c2_default7", RT.DEATH_SCRIPT):
                bp["ScriptDeath"] = G.resref(RT.DEATH_SCRIPT)       # credits the kill, then runs the standard death script
            else:
                cs.warnings.append(f"{what}: ScriptDeath is {script_death!r}: add `AdvanceQuest(OBJECT_SELF, oPC, "
                                   f"{slot})` for the killer's party to it, or the kill will not advance the quest")
        elif script_death != "ai_ondeath":
            cs.warnings.append(f"{what}: ScriptDeath is {script_death!r}, not ai_ondeath - quest_kill credit is "
                               "done in ai_ondeath/party_credit, so the kill may not advance the quest")
        cs.save("utc", res, _sort_top(bp), note=f"kill target {res}")

        def patch(inst: dict) -> None:
            sync_vars(inst, tag, wanted)

        patched = self._patch_instances(cs, res, patch) if mode == "existing" else 0
        if mode == "new":
            if t.get("place"):
                self._defer_place(res, t["place"], what)
            else:
                cs.notes.append(f"{what} was created but not placed: put it in an area, or add it as a unique to an "
                                "encounter blueprint")
        report["targets"].append({"resref": res, "mode": mode, "stage": st["n"], "slot": slot,
                                  "instances_patched": patched})

    # --------------------------------------------------------------- pickup
    def _wire_pickup(self, cs: ChangeSet, spec: dict, st: dict, report: dict) -> None:
        tag = spec["tag"]
        it = dict(st.get("item") or {})
        res = check_new_resref(it.get("resref", ""), "quest item resref")
        if self._exists(cs, "uti", res):
            uti = cs.load("uti", res)
            if not str(G.get(uti, "Comment", "")).startswith(MARK):
                raise QuestError(f"quest item {res!r} already exists and was not generated by this tool")
        else:
            base = it.get("clone_from") or (RT.ITEM_TEMPLATE if self.generic else ITEM_TEMPLATE)
            if not self._exists(cs, "uti", base):
                raise QuestError(f"quest item template {base!r} not found in src/uti")
            uti = cs.load("uti", base)
            strip_all_quest_vars(uti)
        name = _txt(it, "name") or res
        desc = _txt(it, "description")
        uti["TemplateResRef"] = G.resref(res)
        uti["Tag"] = G.cexostring("quest")  # on_item_acq only advances items tagged "quest"
        uti["LocalizedName"] = G.locstring(name)
        if desc:
            uti["Description"] = G.locstring(desc)
            uti["DescIdentified"] = G.locstring(desc)
        uti["Comment"] = G.cexostring(f"{MARK}: quest {tag}")
        sync_vars(uti, tag, stage_vars(tag, st, 1))  # on_item_acq always advances slot 1
        cs.save("uti", res, _sort_top(uti), note=f"quest item {res}")
        dropped = it.get("dropped_by") or st.get("dropped_by")
        info = {"resref": res, "stage": st["n"], "dropped_by": dropped or ""}
        if dropped:
            if not self._exists(cs, "utc", dropped):
                raise QuestError(f"dropped_by creature {dropped!r} not found in src/utc")
            bp = cs.load("utc", dropped)
            lst = bp.get("ItemList") or G.list_()
            bp["ItemList"] = lst
            if not any(G.get(e, "InventoryRes") == res for e in lst["value"]):
                n = len(lst["value"])
                lst["value"].append(G.struct(n, InventoryRes=G.resref(res), Repos_PosX=G.word(n % 10),
                                             Repos_Posy=G.word(n // 10)))
            cs.save("utc", dropped, _sort_top(bp), note=f"carries quest item {res}")
            cs.notes.append(f"{dropped} now carries {res}; creatures respawn from the blueprint so no instance patch "
                            "is needed")
        else:
            cs.notes.append(f"quest item {res} must be placed somewhere (loot, container, or a creature's inventory)")
        report["items"].append(info)

    # -------------------------------------------------------------- explore
    def _wire_explore(self, cs: ChangeSet, spec: dict, st: dict, report: dict) -> None:
        tag = spec["tag"]
        area = str(st.get("area", ""))
        if not self._exists(cs, "git", area):
            raise QuestError(f"stage {st['n']}: explore area {area!r} not found")
        git = cs.load("git", area)
        if self.generic:
            self._wire_explore_generic(cs, spec, st, report, area, git)
            return
        cur = G.get_var(git, "enter_script")
        if cur and cur != GENERIC_ENTER:
            raise QuestError(f"area {area} already has enter_script = {cur!r}; add AdvanceQuest(OBJECT_SELF, oPC, N) "
                             "to that script by hand instead")
        slot = pick_slots(G.vars_of(git), [], tag, [st["n"]])[st["n"]]
        sync_vars(git, tag, stage_vars(tag, st, slot))
        G.set_var(git, "enter_script", GENERIC_ENTER)
        cs.save("git", area, git, note=f"explore stage {st['n']} of {tag}")
        if cs.pending_text(cs.rel_nss(GENERIC_ENTER)) is None:
            cs.save_nss(GENERIC_ENTER, GENERIC_ENTER_SRC, note="generic area quest advancer")
        report["explore"].append({"area": area, "stage": st["n"], "slot": slot})

    def _wire_explore_generic(self, cs: ChangeSet, spec: dict, st: dict, report: dict, area: str, git: dict) -> None:
        """Generic module: the area's own OnEnter script (in the .are) runs enter_quest_adv; the slot variables sit on the area."""
        if not cs.exists("are", area):
            raise QuestError(f"stage {st['n']}: explore area {area!r} has no .are file")
        are = cs.load("are", area)
        cur = G.get(are, "OnEnter", "")
        if cur and cur != GENERIC_ENTER:
            raise QuestError(f"area {area} already has OnEnter = {cur!r}; add AdvanceQuest(OBJECT_SELF, oPC, N) "
                             "to that script by hand instead")
        tag = spec["tag"]
        slot = pick_slots(G.vars_of(git), [], tag, [st["n"]])[st["n"]]
        sync_vars(git, tag, stage_vars(tag, st, slot))
        cs.save("git", area, git, note=f"explore stage {st['n']} of {tag}")
        if cur != GENERIC_ENTER:
            are["OnEnter"] = G.resref(GENERIC_ENTER)
            cs.save("are", area, are, note=f"area OnEnter -> {GENERIC_ENTER}")
        report["explore"].append({"area": area, "stage": st["n"], "slot": slot})

    # ---------------------------------------------------------------- notes
    def _notes(self, cs: ChangeSet, spec: dict) -> None:
        rewards = [(s["n"], s["reward"]) for s in spec["stages"] if s["reward"]]
        for n, rw in rewards:
            if rw.get("item") and not self._exists(cs, "uti", rw["item"]):
                cs.warnings.append(f"stage {n}: reward item {rw['item']!r} not found in src/uti (base-game item?)")
        if not rewards:
            cs.warnings.append("no rewards configured on any stage (players get nothing for completing it)")


def describe(spec: dict) -> list[dict]:
    """Human-readable stage mechanism list for previews (no project access needed)."""
    s = normalize(spec)
    out = []
    for st in s["stages"]:
        via = st["via"]
        if via == "talk":
            who = (st.get("npc") or {}).get("resref") or s["giver"]["resref"]
            how = f"talk to {who}"
        elif via == "kill":
            how = f"kill {(st.get('target') or {}).get('resref', '?')}"
        elif via == "pickup":
            how = f"pick up {(st.get('item') or {}).get('resref', '?')}"
        else:
            how = f"enter area {st.get('area', '?')}"
        out.append({"stage": st["n"], "style": s["script_style"], "how": how, "journal": st["journal"], "reward": st["reward"],
                    "end": st["n"] == s["stages"][-1]["n"]})
    return out
