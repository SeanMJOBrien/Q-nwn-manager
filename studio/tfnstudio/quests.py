"""Quest specs -> change sets for TFN's variable-driven quest system (inc_quest.nss).

A quest is a journal category plus *stage wiring*: the object that advances stage N carries the
local variable `questK = "<NN>_<tag>"` (K = a free slot on that object) and optional
`questK_reward_*` / `questK_prereqM` variables.  Mechanisms (all pre-existing TFN scripts):

  talk     NPC dialog nodes using dlg_q_chk_eli / dlg_q_adv / dlg_q_chk_at (params `target`=K); spec `script_style`
           "legacy" uses TFN's slot-numbered dlg_q_chk_atcN instead of dlg_q_chk_at
  kill     creature var `questK` + `quest_kill = K` (ai_ondeath credits the killing party)
  pickup   item with Tag `quest` + `quest1`; optionally carried by a creature (ItemList)
  explore  area var `questK` + area var `enter_script = enter_quest_adv` (generic helper we ship)

Spec shape (see specs/quests/*.json for examples):
  {"tag": "q_wolf_hunt", "name": "...", "priority": 2,
   "giver": {"mode": "new|existing", "resref": "...", "name": "...", "clone_from": "<utc>",
             "greeting": "...", "place": {"area", "x", "y", "facing"}},
   "stages": [{"n": 1, "via": "talk", "journal": "...", "offer": "...", ...}, ...]}
"""

from __future__ import annotations

