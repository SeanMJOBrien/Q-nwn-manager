TAG_RE = re.compile(r"^[qb]_[a-z0-9_]{1,25}$")
MARK = "tfn-content-studio"
VIAS = ("talk", "kill", "pickup", "explore")
MAX_SLOT = 19
GENERIC_ENTER = "enter_quest_adv"
GENERIC_AT = "dlg_q_chk_at"
STYLES = ("modern", "legacy")
ITEM_TEMPLATE = "q_brain"
STAGE_RE = re.compile(r"^(\d\d)_([qb]_[A-Za-z0-9_]+)$")

GENERIC_ENTER_SRC = """\
// Generic "explore" quest advancer for areas (generated by tfn-content-studio).
// Set the area's `enter_script` variable to this script and put `questN` variables
// (e.g. quest1 = "02_q_example") on the area; every PC entering advances those stages.
#include "inc_quest"

void main()
{
    object oPC = GetEnteringObject();

    if (!GetIsPC(oPC)) return;

    int i;
    for (i = 1; i < HIGHEST_QUEST_COUNT; i++)
    {
        if (GetLocalString(OBJECT_SELF, "quest" + IntToString(i)) != "")
            AdvanceQuest(OBJECT_SELF, oPC, i);
    }
}
"""

GENERIC_AT_SRC = """\
// Returns TRUE if the PC is CURRENTLY at the quest stage held in questK on this object (generated by tfn-content-studio).
// Param: "target" -> K, the quest slot number. One script for every slot (replaces dlg_q_chk_atc1..9).
#include "inc_quest"

int StartingConditional()
{
    object oPC = GetPCSpeaker();

    int nTarget = StringToInt(GetScriptParam("target"));

    if (nTarget == 0)
        return FALSE;

    return GetIsCurrentlyAtQuestStage(OBJECT_SELF, oPC, nTarget);
}
"""


class QuestError(ProjectError):
    """Invalid quest spec or an unresolvable conflict with existing content."""


def stage_value(stage: int, tag: str) -> str:
    return f"{stage:02d}_{tag}"


# ---------------------------------------------------------------------------
# spec normalisation
# ---------------------------------------------------------------------------

def _txt(d: dict, key: str, default: str = "") -> str:
    """Trimmed text of `d[key]`, or `default` when it is missing or blank (the UI sends "" for untouched fields)."""
    v = d.get(key)
    s = "" if v is None else str(v).strip()
    return s or default


def normalize(spec: dict) -> dict:
    if not isinstance(spec, dict):
        raise QuestError("spec must be an object")
    tag = _txt(spec, "tag")
    if not TAG_RE.match(tag) or len(tag) > 27:
        raise QuestError("tag must look like q_something / b_something (a-z, 0-9, _; at most 27 chars)")
    name = _txt(spec, "name")
    if not name:
        raise QuestError("quest needs a name")
    out: dict[str, Any] = {"tag": tag, "name": name, "kind": "bounty" if tag.startswith("b_") else "quest"}
    pr = spec.get("priority")
    out["priority"] = int(pr) if pr is not None else (0 if tag.startswith("b_") else 2)
    if not 0 <= out["priority"] <= 4:
        raise QuestError("priority must be 0-4")

    stages_in = spec.get("stages") or []
    if not stages_in:
        raise QuestError("quest needs at least one stage")
    stages = []
    for st in stages_in:
        try:
            n = int(st.get("n"))
        except (TypeError, ValueError):
            raise QuestError("every stage needs a numeric `n`")
        via = st.get("via", "talk")
        if via not in VIAS:
            raise QuestError(f"stage {n}: via must be one of {VIAS}")
        journal = _txt(st, "journal")
        if not journal:
            raise QuestError(f"stage {n}: journal text is required")
        s = dict(st)
        s.update({"n": n, "via": via, "journal": journal})
        rw = st.get("reward") or {}
        s["reward"] = {k: rw[k] for k in ("xp_tier", "xp_level", "gold", "item") if rw.get(k) not in (None, "", 0)}
        if "xp_tier" in s["reward"] and not 1 <= int(s["reward"]["xp_tier"]) <= 4:
            raise QuestError(f"stage {n}: xp_tier must be 1-4")
        if "xp_tier" in s["reward"] and "xp_level" not in s["reward"]:
            raise QuestError(f"stage {n}: xp_tier needs xp_level too (both are required for XP)")
        stages.append(s)
    stages.sort(key=lambda s: s["n"])
    nums = [s["n"] for s in stages]
    if nums != list(range(1, len(nums) + 1)):
        raise QuestError(f"stage numbers must be consecutive starting at 1 (got {nums}); "
                         "TFN requires the PC to be at stage N-1 unless a jumpstage is hand-wired")
    if len(nums) > 99:
        raise QuestError("at most 99 stages")
    if stages[0]["via"] != "talk":
        raise QuestError("stage 1 must be `talk` (the giver offers the quest)")
    out["stages"] = stages

    # Specs without `script_style` are older ones: they keep the slot-numbered scripts they were built with.
    style = spec.get("script_style") or "legacy"
    if style not in STYLES:
        raise QuestError(f"script_style must be one of {STYLES}")
    out["script_style"] = style

    giver = dict(spec.get("giver") or {})
    giver.setdefault("mode", "new")
    if giver["mode"] not in ("new", "existing"):
        raise QuestError("giver.mode must be new or existing")
    if not re.match(r"^[A-Za-z0-9_]{1,32}$", str(giver.get("resref", ""))):
        raise QuestError("giver needs a `resref`")
    out["giver"] = giver
    return out


# ---------------------------------------------------------------------------
# variable helpers
# ---------------------------------------------------------------------------

def quest_slots(vars_: dict) -> dict[int, str]:
    out = {}
    for k, v in vars_.items():
        m = re.match(r"^quest(\d{1,2})$", k)
        if m and isinstance(v, str):
            out[int(m.group(1))] = v
    return out


def owned_names(owner: dict, tag: str) -> set[str]:
    """Names of the `questK` / `questK_*` variables that belong to quest `tag` on this object."""
    names: set[str] = set()
    vars_ = G.vars_of(owner)
    for slot, val in quest_slots(vars_).items():
        m = STAGE_RE.match(val)
        if m and m.group(2) == tag:
            names.add(f"quest{slot}")
            names |= {k for k in vars_ if k.startswith(f"quest{slot}_")}
    return names


def strip_quest_vars(owner: dict, tag: str) -> int:
    """Remove every variable that belongs to quest `tag`. Returns how many were removed."""
    removed = 0
    for name in owned_names(owner, tag):
        removed += int(G.del_var(owner, name))
    return removed


def strip_all_quest_vars(owner: dict) -> None:
    """Forget every quest variable (used when cloning a blueprint that served other quests)."""
    for slot in list(quest_slots(G.vars_of(owner))):
        G.del_var(owner, f"quest{slot}")
        G.del_vars_with_prefix(owner, f"quest{slot}_")
    G.del_var(owner, "quest_kill")


def first_free_slot(used: set[int]) -> int:
    for k in range(1, MAX_SLOT + 1):
        if k not in used:
            return k
    raise QuestError(f"no free quest slot (1-{MAX_SLOT} all in use) on one object")


def stage_vars(tag: str, stage: dict, slot: int) -> dict[str, Any]:
    """The complete set of variables that wire `stage` to `slot` on its advancing object."""
    out: dict[str, Any] = {f"quest{slot}": stage_value(stage["n"], tag)}
    rw = stage.get("reward") or {}
    if rw.get("xp_tier"):
        out[f"quest{slot}_reward_xp_tier"] = int(rw["xp_tier"])
        out[f"quest{slot}_reward_xp_level"] = int(rw["xp_level"])
    if rw.get("gold"):
        out[f"quest{slot}_reward_gold"] = int(rw["gold"])
    if rw.get("item"):
        out[f"quest{slot}_reward_item"] = str(rw["item"])
    for m, pre in enumerate(stage.get("prereq") or [], start=1):
        out[f"quest{slot}_prereq{m}"] = stage_value(int(pre["stage"]), pre["quest"])
    if stage.get("nohighlight"):
        out[f"quest{slot}_nohighlight"] = 1
    return out


def sync_vars(owner: dict, tag: str, wanted: dict[str, Any]) -> None:
    """Make `owner` carry exactly `wanted` for quest `tag`: drop stale owned vars, set the rest in place.

    Setting in place keeps the VarTable order stable, so re-running an unchanged spec changes nothing.
    """
    for name in owned_names(owner, tag) - wanted.keys():
        G.del_var(owner, name)
    for name, val in wanted.items():
        G.set_var(owner, name, val)


def pick_slots(owner_vars: dict, other_vars: list[dict], tag: str, stage_numbers: list[int]) -> dict[int, int]:
    """Slot per stage: reuse the slot already holding this stage on the owner, else the first free one."""
    mine = {}
    for slot, val in quest_slots(owner_vars).items():
        m = STAGE_RE.match(val)
        if m and m.group(2) == tag:
            mine[int(m.group(1))] = slot
    used: set[int] = set(quest_slots(owner_vars))
    for ov in other_vars:
        used |= set(quest_slots(ov))
    out: dict[int, int] = {}
    for n in stage_numbers:
        if n in mine:
            out[n] = mine[n]
    for n in stage_numbers:
        if n not in out:
            slot = first_free_slot(used | set(out.values()))
            out[n] = slot
    return out


def _locname(name: str) -> dict:
    return G.locstring(name)


def _sort_top(d: dict) -> dict:
    out = {}
    if "__data_type" in d:
        out["__data_type"] = d["__data_type"]
    for k in sorted((k for k in d if k != "__data_type"), key=str.lower):
        out[k] = d[k]
    return out


