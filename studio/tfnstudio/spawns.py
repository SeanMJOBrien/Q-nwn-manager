"""Encounter blueprints (.ute) as TFN uses them: a data container for random spawn groups.

`area_init` reads the UTE's CreatureList (SingleSpawn=1 -> "unique" pool, else "common"),
`DifficultyIndex` (0-4 -> unique chance 5/10/15/20/25 %) and the `rare` variable;
`area_refresh` then spawns (spawns + up to 25 % extra) creatures, and with 15 % chance
replaces one with the group's rare.  See SPAWN_SYSTEM.md in the TFN repo.
"""

from __future__ import annotations

from . import gffjson as G
from .index import DIFFICULTY_NAMES, UNIQUE_CHANCE
from .project import ProjectError, TfnProject, check_new_resref

TEMPLATE_UTE = "bandit_moderate"
RARE_CHANCE = 15          # percent per refresh (CHANCE_OF_RARE_SPAWN in area_refresh.nss)
EXTRA_SPAWN_FRACTION = 0.25
MAX_GROUPS = 9


class PlanError(ProjectError):
    """A user-supplied spec is invalid."""


def _creature_facts(project: TfnProject, resref: str) -> tuple[float, int, bool]:
    """(CR, appearance, known) for a creature blueprint."""
    if project.exists("utc", resref):
        bp = project.read("utc", resref)
        return float(G.get(bp, "ChallengeRating", 1.0)), int(G.get(bp, "Appearance_Type", 0)), True
    return 1.0, 0, False


def build_ute(project: TfnProject, spec: dict, existing: dict | None = None) -> tuple[dict, list[str]]:
    """Return (ute_json, warnings) for `spec`.

    spec = {resref, name?, difficulty 0-4, creatures:[{resref, unique?}], rare?, template?}
    Starts from `existing` (preserving fields we don't manage) or a copy of a real TFN UTE.
    """
    warnings: list[str] = []
    resref = check_new_resref(spec.get("resref", ""), "encounter resref")
    difficulty = int(spec.get("difficulty", 2))
    if difficulty not in DIFFICULTY_NAMES:
        raise PlanError("difficulty must be 0 (very easy) .. 4 (impossible)")
    creatures = spec.get("creatures") or []
    if not creatures:
        raise PlanError("an encounter needs at least one creature")
    if all(c.get("unique") for c in creatures):
        raise PlanError("at least one creature must be common (not unique), otherwise the common pool is empty")
    if existing is not None:
        ute = G.clone(existing)
    else:
        tmpl = spec.get("template") or TEMPLATE_UTE
        if not project.exists("ute", tmpl):
            raise PlanError(f"template encounter {tmpl!r} not found in src/ute")
        ute = project.read("ute", tmpl)
        ute["Comment"] = G.cexostring("Generated by tfn-content-studio")
        ute.pop("VarTable", None)
    name = (spec.get("name") or resref).strip()
    ute["TemplateResRef"] = G.resref(resref)
    ute["Tag"] = G.cexostring(resref)
    ute["LocalizedName"] = G.locstring(name)
    ute["DifficultyIndex"] = G.int_(difficulty)
    ute["Difficulty"] = G.int_(0)

    entries = []
    seen = set()
    for c in creatures:
        res = c.get("resref", "")
        check_new_resref(res, "creature resref") if not project.exists("utc", res) else None
        if res in seen:
            raise PlanError(f"creature {res!r} listed twice")
        seen.add(res)
        cr, app, known = _creature_facts(project, res)
        if not known:
            warnings.append(f"creature {res!r} not found in src/utc (base-game creature?); CR/appearance default")
        entries.append(G.struct(0, Appearance=G.int_(app), CR=G.float_(cr), ResRef=G.resref(res),
                               SingleSpawn=G.byte(1 if c.get("unique") else 0)))
    ute["CreatureList"] = G.list_(entries)

    rare = spec.get("rare") or ""
    if rare:
        if not project.exists("utc", rare):
            warnings.append(f"rare creature {rare!r} not found in src/utc")
        G.set_var(ute, "rare", rare)
    elif existing is not None:
        G.del_var(ute, "rare")
    if "VarTable" in ute and not ute["VarTable"]["value"]:
        del ute["VarTable"]
    # keep nasher's usual key order (case-insensitive) after __data_type
    ordered = {"__data_type": ute.get("__data_type", G.cexostring("UTE ")["value"])}
    for k in sorted((k for k in ute if k != "__data_type"), key=str.lower):
        ordered[k] = ute[k]
    return ordered, warnings


def describe_ute(ute: dict) -> dict:
    """Plain summary used by the UI and expected-mix maths."""
    entries = (ute.get("CreatureList") or {}).get("value", [])
    commons = [{"resref": G.get(c, "ResRef"), "cr": G.get(c, "CR", 0.0)} for c in entries if not G.get(c, "SingleSpawn", 0)]
    uniques = [{"resref": G.get(c, "ResRef"), "cr": G.get(c, "CR", 0.0)} for c in entries if G.get(c, "SingleSpawn", 0)]
    diff = G.get(ute, "DifficultyIndex", 2)
    return {"resref": G.get(ute, "TemplateResRef"), "difficulty": diff, "difficulty_name": DIFFICULTY_NAMES.get(diff, "?"),
            "unique_chance": UNIQUE_CHANCE.get(diff, 5), "commons": commons, "uniques": uniques,
            "rare": G.get_var(ute, "rare", "")}


def expected_mix(ute_desc: dict, spawns: int) -> dict:
    """Expected creature counts for one refresh of a group configured with `spawns`."""
    n_total = spawns * (1 + EXTRA_SPAWN_FRACTION / 2)  # "this + up to 25% extra"
    uc = ute_desc["unique_chance"] / 100.0 if ute_desc["uniques"] else 0.0
    mix: dict[str, float] = {}
    commons, uniques = ute_desc["commons"], ute_desc["uniques"]
    for c in commons:
        mix[c["resref"]] = n_total * (1 - uc) / len(commons)
    for u in uniques:
        mix[u["resref"]] = n_total * uc / len(uniques)
    avg_cr = (sum(c["cr"] for c in commons) / len(commons)) if commons else 0.0
    rows = [{"resref": r, "expected": round(v, 2)} for r, v in sorted(mix.items(), key=lambda kv: -kv[1])]
    return {"spawns_min": spawns, "spawns_max": int(spawns * (1 + EXTRA_SPAWN_FRACTION)), "expected_total": round(n_total, 1),
            "avg_common_cr": round(avg_cr, 2), "rows": rows,
            "rare": ute_desc["rare"], "rare_chance": RARE_CHANCE if ute_desc["rare"] else 0}


def usage(areas: dict[str, dict], ute_resref: str) -> list[dict]:
    """Areas whose spawn groups use this encounter blueprint."""
    out = []
    for a in areas.values():
        for g in a.get("groups") or []:
            if g.get("ute") == ute_resref:
                out.append({"area": a["resref"], "name": a.get("name", ""), "group": g["n"],
                            "spawns": g.get("spawns", 0), "cr": a.get("cr")})
    return sorted(out, key=lambda r: r["area"])


def cr_check(ute_desc: dict, area_cr: int | None) -> list[str]:
    """Advisory: compare creature CRs with the area's `cr` variable."""
    notes = []
    if area_cr is None:
        return notes
    for c in ute_desc["commons"] + ute_desc["uniques"]:
        if c["cr"] > area_cr + 3:
            notes.append(f"{c['resref']} (CR {c['cr']:g}) is far above the area cr {area_cr}")
        elif c["cr"] < area_cr - 6:
            notes.append(f"{c['resref']} (CR {c['cr']:g}) is far below the area cr {area_cr}")
    return notes
